#!/usr/bin/env node
/**
 * Local development PostgreSQL lifecycle helper.
 *
 * Uses the portable PostgreSQL binaries shipped by the `embedded-postgres`
 * dev dependency. Data lives in `.pglocal/` (gitignored). Production should
 * simply point DATABASE_URL at a managed PostgreSQL instance instead.
 *
 * Usage: node scripts/local-db.mjs [init|start|stop|status|createdb]
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pgHome = path.join(root, "node_modules", "@embedded-postgres", "windows-x64", "native");
const bin = path.join(pgHome, "bin");
const dataDir = path.join(root, ".pglocal", "data");
const logFile = path.join(root, ".pglocal", "postgres.log");
const port = Number(process.env.PGPORT || 5432);
const superuser = "postgres";

function exe(name) {
  return process.platform === "win32" ? path.join(bin, `${name}.exe`) : path.join(bin, name);
}

function run(cmd, args, opts = {}) {
  const res = spawnSync(cmd, args, { stdio: "inherit", cwd: root, ...opts });
  if (res.error) throw res.error;
  if (res.status !== 0) process.exit(res.status ?? 1);
}

function init() {
  if (fs.existsSync(path.join(dataDir, "PG_VERSION"))) {
    console.log("Database cluster already initialized at .pglocal/data");
    return;
  }
  fs.mkdirSync(dataDir, { recursive: true });
  console.log("Initializing PostgreSQL cluster...");
  run(exe("initdb"), [
    "-D", dataDir,
    "-U", superuser,
    "-A", "trust",
    "-E", "UTF8",
    "--locale=C",
  ]);
  appendConfig();
}

function appendConfig() {
  const confPath = path.join(dataDir, "postgresql.conf");
  let conf = fs.readFileSync(confPath, "utf8");
  conf += [
    "",
    "# --- rzilient local dev settings (generated by scripts/local-db.mjs) ---",
    `port = ${port}`,
    "listen_addresses = '127.0.0.1'",
    "logging_collector = off",
    "log_min_messages = warning",
  ].join("\n");
  fs.writeFileSync(confPath, conf);
}

function start() {
  if (!fs.existsSync(path.join(dataDir, "PG_VERSION"))) init();
  fs.mkdirSync(path.dirname(logFile), { recursive: true });
  console.log(`Starting PostgreSQL on 127.0.0.1:${port}...`);
  run(exe("pg_ctl"), [
    "-D", dataDir,
    "-l", logFile,
    "-w",
    "start",
  ]);
}

function stop() {
  console.log("Stopping PostgreSQL...");
  run(exe("pg_ctl"), ["-D", dataDir, "-w", "stop", "-m", "fast"]);
}

function status() {
  const res = spawnSync(exe("pg_ctl"), ["-D", dataDir, "status"], { encoding: "utf8" });
  console.log(res.stdout || res.stderr || "not running");
  process.exit(0);
}

async function createdb() {
  const dbName = process.env.PGDATABASE_NAME || "rzilient";
  const { default: pg } = await import("pg");
  const admin = new pg.Client({
    connectionString: `postgresql://${superuser}@127.0.0.1:${port}/postgres`,
  });
  await admin.connect();
  const existing = await admin.query("SELECT 1 FROM pg_database WHERE datname = $1", [dbName]);
  if (existing.rowCount === 0) {
    await admin.query(`CREATE DATABASE "${dbName}"`);
    console.log(`Created database "${dbName}".`);
  } else {
    console.log(`Database "${dbName}" already exists.`);
  }
  await admin.end();
}

const cmd = process.argv[2] || "start";
try {
  if (cmd === "init") init();
  else if (cmd === "start") start();
  else if (cmd === "stop") stop();
  else if (cmd === "status") status();
  else if (cmd === "createdb") await createdb();
  else {
    console.error(`Unknown command: ${cmd}`);
    process.exit(1);
  }
} catch (err) {
  console.error(err.message || err);
  process.exit(1);
}
